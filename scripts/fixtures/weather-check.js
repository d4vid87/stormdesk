import '../js/boot.js';
import { notifHistory } from '../js/app.js';
import { forecast } from '../js/desk.js';
import { refreshBoards } from '../js/boards.js';
import { chart } from '../js/charts.js';
const $ = id => document.getElementById(id);
const check = (v, message) => { if (!v) throw Error(message); };
const wait = () => new Promise(resolve => setTimeout(resolve, 100));
try {
  await wait();
  check(!notifHistory().some(n => /High wind|Frost expected|Snow \/ ice/.test(n.title)), 'Saved weather does not trigger fresh warnings');
  check(forecast()?._cached, 'Saved forecast paints while network is pending');
  check($('hero-live').textContent.includes('Saved data'), 'Saved weather is labelled');
  check($('forecast-coverage').textContent.includes('Saved forecast'), 'Saved forecast label is visible outside details');
  check(!requests.some(u => u.includes('ensemble-api')), 'Closed advanced outlook makes no ensemble request');
  check(!requests.some(u => u.includes('models=') && u.includes('ensemble-api')), 'No hidden ensemble work');
  document.querySelector('#daycards .daycard').scrollIntoView();
  await wait(); await wait();
  const day = document.querySelector('#daycards .daycard');
  check(day.querySelector('.dc-agreement').textContent.includes('Wide'), `Model differences appear beside the day: ${day.dataset.agreement}; requests=${requests.filter(u=>u.includes('models=')).length}; forecastTop=${$('observatory-forecast').getBoundingClientRect().top}`);
  day.click();
  check($('forecast-dialog').textContent.includes('not accuracy'), 'Agreement explains its limits');
  $('forecast-dialog').close();
  check(document.querySelector('#daycards .daycard:last-child').dataset.agreement.includes('unavailable'), 'Days outside model coverage say unavailable');
  const fc = forecast(), now = Math.floor(Date.now()/1000);
  const o = [now,0,3,6,180,60,1010,20,60,0,2,100,.1,0,0,0,2.6,1,2];
  dispatchEvent(new CustomEvent('wd:ws-obs',{detail:o}));
  await wait();
  document.querySelector('[data-metric="windAvg"]').click();
  check($('detail-blurb').textContent.includes('Station observation'), 'Reading detail identifies station source');
  $('detail-close').click();
  document.querySelector('[data-metric="dew"]').click();
  check($('detail-blurb').textContent.includes('Forecast estimate'), 'Unmeasured fields retain forecast provenance');
  $('detail-close').click();
  check(['advanced-outlook','observatory-signals','activity-planner'].every(id => getComputedStyle($(id)).display === 'none'), 'Retired Weather sections are not displayed');
  check(!requests.some(u=>u.includes('ensemble-api')), 'Removed model section performs no hidden ensemble work');
  document.querySelector('.tab[data-section="data"]').click();
  $('history-range').value='24'; $('history-range').dispatchEvent(new Event('change',{bubbles:true}));
  $('history-compare').value='previous'; await refreshBoards();
  check($('history-comparison-status').textContent.includes('Dashed purple'), 'Previous-period comparison is labelled');
  const ranges = requests.filter(u=>u.includes('/history/tuples?from=')).map(u=>new URL(u));
  check(ranges.some(u=>+u.searchParams.get('to')- +u.searchParams.get('from') === 86400), 'Comparison requests only selected range');
  check($('snapshot-temp').textContent !== '—', 'Current readings survive comparison load');
  const canvas = $('c-temp'), pick = canvas._wdOpts.onPick, at = Date.now();
  const series = [
    {name:'current', color:'#43cfc3', data:[{x:at,y:0},{x:at+3600000,y:0}]},
    {name:'previous', color:'#b49be7', dash:[5,4], data:[{x:at,y:10,sourceX:at-86400000},{x:at+3600000,y:10,sourceX:at+3600000-86400000}]},
  ];
  canvas.scrollIntoView(); await wait();
  chart(canvas, series, {onPick:pick});
  const clickReading = (x, y) => {
    const rect = canvas.getBoundingClientRect();
    canvas.dispatchEvent(new MouseEvent('click', {bubbles:true,clientX:rect.left+x,clientY:rect.top+y}));
  };
  const highY = 8 + (canvas.clientHeight - 24) / 12;
  const lowY = 8 + (canvas.clientHeight - 24) * 11 / 12;
  clickReading(35, highY);
  check($('detail-title').textContent.includes(new Date(at-86400000).toLocaleString([],{weekday:'short',month:'short',day:'numeric'})), 'Clicking comparison line opens original timestamp');
  $('detail-close').click();
  clickReading(35, lowY);
  check($('detail-title').textContent.includes(new Date(at).toLocaleString([],{weekday:'short',month:'short',day:'numeric'})), 'Clicking current line opens current timestamp');
  $('detail-close').click();
  let selected = null;
  chart(canvas, series, {onPick:(p,name)=>{selected={p,name};}});
  clickReading(34 + (canvas.clientWidth - 40) / 2, highY);
  check(selected?.name === 'previous' && Number.isFinite(selected.p.sourceX), 'Sparse comparison line selects a real historical sample between endpoints');
  selected = null;
  clickReading(5, highY);
  check(selected === null, 'Clicks outside the plot do not select readings');
  chart(canvas, [{...series[0],type:'bar',data:series[0].data.map(p=>({...p,y:5}))}, series[1]], {onPick:(p,name)=>{selected={p,name};}});
  clickReading(35, lowY);
  check(selected?.name === 'current', 'Clicking inside a rain bar selects that series');
  chart(canvas, [], {onPick:pick});
  clickReading(35, highY);
  check(!$('detail').classList.contains('open'), 'Empty charts cannot select an old reading');
  $('history-compare').value='year'; await refreshBoards();
  check($('history-comparison-status').textContent.includes('Dashed purple'), 'Previous-year comparison loads');
  window.failHistory=true;
  $('history-range').value='168'; $('history-range').dispatchEvent(new Event('change',{bubbles:true}));
  await refreshBoards();
  check($('history-comparison-status').textContent.includes('Comparison unavailable'), 'Missing earlier history has an explicit error');
  check($('snapshot-temp').textContent !== '—', 'Comparison failure preserves primary period');
  window.failHistory=false;
  dispatchEvent(new CustomEvent('wd:alerts',{detail:[{properties:{event:'Tornado Warning',description:'Take shelter',severity:'Extreme'},geometry:{type:'Polygon',coordinates:[[[-98,35],[-97,35],[-97,36],[-98,35]]]}}]}));
  $('radar-banner-details').click();
  check($('radar-alert-dialog').textContent.includes('Take shelter'), 'Warning instructions are readable');
  $('radar-alert-list').querySelector('button').click();
  check(!$('radar-alert-dialog').open && $('lab').classList.contains('active'), 'Warning action opens radar');
  check($('lab-frame').src.includes('-97.5,35.5,7'), 'Radar centers the warning geometry');
  document.querySelector('.tab[data-section="desk"]').click();
  $('desk').scrollTop = 0;
  await wait();
  check(document.documentElement.scrollWidth <= innerWidth, 'Weather layout fits the viewport');
  document.body.dataset.weatherCheck='ok';
} catch(error) { document.body.dataset.weatherCheck=error.message; console.error(error); }
