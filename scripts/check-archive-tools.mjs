import assert from 'node:assert/strict';
import {parseCSV,quality,usable,gaps,storms,activityWindows} from '../site/js/archive-tools.js';
const row=(ts,temp=20,rain=0)=>{const r=Array(19).fill(null);Object.assign(r,{0:ts,3:8,7:temp,12:rain,15:0,17:1});return r;};
assert.equal(parseCSV('time,temp,pressure\n100,20,1000').rows[0][7],20);
const us=parseCSV('dateTime,outTemp,windSpeed,pressure,rain\n100,68,10,29.53,1','us');
assert.equal(us.rows[0][7],20);assert.equal(us.rows[0][12],25.4);assert.ok(Math.abs(us.rows[0][2]-4.4704)<1e-9);
const wx=parseCSV('dateTime,outTemp,windSpeed,barometer,pressure,rain\n100,20,36,1013,985,0.5','weewx-metric');
assert.equal(wx.rows[0][6],985);assert.equal(wx.rows[0][2],10);assert.equal(wx.rows[0][12],5);assert.deepEqual(wx.ignored,['barometer']);
assert.equal(parseCSV('ts,temp\r\n"100","20"\r\n100,21').duplicates,1);
assert.throws(()=>parseCSV('ts,temp\n2020-01-01T12:00,20','si','explicit'),/offset/);
assert.throws(()=>parseCSV('ts,temp\n100,nope'),/invalid temp/);
assert.throws(()=>parseCSV('ts,temp\n100,"20'),/Unclosed/);
assert.throws(()=>parseCSV('ts,temp,temp\n100,20,21'),/Duplicate/);
assert.equal(parseCSV('ts,temp\n2020-01-01T12:00:00-06:00,20').rows[0][0],Date.parse('2020-01-01T18:00:00Z')/1000);
assert.equal(quality([row(100,999)]).length,1);
const stuck=Array.from({length:73},(_,i)=>row(100+i*300));assert.ok(quality(stuck).some(x=>x.text.includes('stuck')));
assert.deepEqual(usable([row(1),row(2),row(3)],[{kind:'exclude',ts:2,until:2}]).map(x=>x[0]),[1,3]);
assert.equal(gaps([row(0),row(60),row(600)],0,600).length,1);
assert.equal(storms([row(100,20,1),row(160,20,2),row(30000,20,3)]).length,2);
assert.equal(storms([row(100,20,1),row(160,20,2)])[0].rain,3);
const h=t=>({time:t,temp:20,wind:2,rain:0,daylight:true}),limits={minTemp:5,maxTemp:25,wind:5,rain:20,daylight:true};
assert.equal(activityWindows([h(0),h(3600000),h(10800000)],limits).length,2,'missing hour breaks the window');
assert.equal(activityWindows([{...h(0),rain:null}],limits).length,0);
assert.equal(activityWindows([{...h(0),daylight:false}],limits).length,0);
console.log('Archive checks passed: CSV source units/time zones, bad data review, exclusions, gaps, storms and activity windows.');
